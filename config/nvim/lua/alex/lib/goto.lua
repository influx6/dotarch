-- Smart "go to definition": a 4-tier fallback chain. LANGUAGE-AGNOSTIC.
--
-- Wired as `gd` for every LSP buffer (plugin-lspconfig.lua's global LspAttach),
-- so it works for any language server -- rust-analyzer, pyright, clangd, HLS,
-- etc. Tiers, tried in order:
--   1. LSP definition. If the server has one, open it through the SAME picker
--      the rest of the config uses (lsp_definitions).
--   2. ripgrep. When editing inside a project, text-search for the symbol under
--      the cursor. This catches definitions the server can't reach (and
--      anything ctags hasn't indexed yet), so local navigation keeps working
--      the moment you open a project -- no index to build. Jump straight to a
--      single hit, pick from several.
--   3. ctags. If a tag exists for the symbol (on the buffer's &tags), open it
--      through the Telescope `tags` picker. Haskell tags are auto-generated by
--      fast-tags (plugin-haskell.lua); other languages just need any tags file.
--   4. Docs fallback (optional, per-filetype). If tiers 1-3 miss and a filetype
--      has registered a doc opener, call it -- e.g. Haskell opens the symbol's
--      Haddock/Hackage page via Hoogle (registered in plugin-haskell.lua). This
--      is the "the source isn't indexed anywhere, but I can still read the docs"
--      tier. Register with M.register_doc_fallback(filetype, fn).
--
-- With no registered doc fallback, tier 4 is skipped and you get a notification
-- -- i.e. for other languages it behaves like `gd` used to until you teach it a
-- doc opener.

local M = {}

--- filetype -> function(word) that opens documentation for `word`.
M.doc_fallbacks = {}

--- Register a tier-4 documentation opener for a filetype (or list of them).
--- @param filetypes string|string[]
--- @param fn fun(word: string)
function M.register_doc_fallback(filetypes, fn)
  if type(filetypes) == "string" then
    filetypes = { filetypes }
  end
  for _, ft in ipairs(filetypes) do
    M.doc_fallbacks[ft] = fn
  end
end

--- Does an exact-match ctags entry exist for `word` on the current buffer's
--- &tags? (Synchronous; respects the buffer-local tag files we set for Haskell.)
local function has_exact_tag(word)
  local pat = "^" .. vim.fn.escape(word, [[\/.*$^~[]]) .. "$"
  local ok, matches = pcall(vim.fn.taglist, pat)
  return ok and type(matches) == "table" and not vim.tbl_isempty(matches)
end

--- A project root for ripgrep, or nil when the buffer isn't inside a project.
--- Prefer a VCS root; otherwise treat the cwd as the project as long as it is
--- not the user's home (a bare `nvim` in ~/ shouldn't rg the whole home dir).
local function project_root(bufnr)
  local root = vim.fs.root(bufnr or 0, { ".git", ".hg", ".svn" })
  if root then
    return root
  end
  local cwd = vim.fn.getcwd()
  if cwd ~= vim.env.HOME then
    return cwd
  end
  return nil
end

--- Parse `rg --line-number --column` output into {filename, lnum, col, text}.
--- Filenames are made absolute against `root` (rg prints them relative to its
--- cwd, which we set to `root`).
local function parse_rg(lines, root)
  local entries = {}
  for _, line in ipairs(lines) do
    local filename, lnum, col, text = line:match("^(.-):(%d+):(%d*):(.*)$")
    if filename then
      if not vim.startswith(filename, "/") then
        filename = root .. "/" .. filename
      end
      table.insert(entries, {
        filename = filename,
        lnum = tonumber(lnum) or 1,
        col = tonumber(col) or 0,
        text = text or "",
      })
    end
  end
  return entries
end

--- Jump to a single ripgrep hit.
local function jump_to(entry)
  vim.cmd("edit +" .. entry.lnum .. " " .. vim.fn.fnameescape(entry.filename))
  if entry.col and entry.col > 0 then
    vim.api.nvim_win_set_cursor(0, { entry.lnum, entry.col - 1 })
  end
end

--- Show several ripgrep hits in the shared quickfix picker.
local function show_ripgrep_results(entries)
  vim.fn.setqflist(entries, " ")
  local ok, builtin = pcall(require, "telescope.builtin")
  if ok then
    builtin.quickfix()
  else
    vim.cmd("copen")
  end
end

--- Tier 3 -> 4: ctags if present, else the filetype's doc fallback.
local function tags_or_docs(word)
  if word == "" then
    return
  end

  if has_exact_tag(word) then
    local ok, builtin = pcall(require, "telescope.builtin")
    if ok then
      builtin.tags({ default_text = word })
    else
      pcall(vim.cmd, "tjump " .. vim.fn.fnameescape(word))
    end
    return
  end

  local fallback = M.doc_fallbacks[vim.bo.filetype]
  if fallback then
    return fallback(word)
  end

  vim.notify("No definition, rg match or tag for '" .. word .. "'", vim.log.levels.WARN, { title = "goto" })
end

--- Tier 2 -> 3 -> 4: ripgrep (in a project), else ctags, else docs.
local function ripgrep_then_tags_then_docs(word)
  -- rg only helps with identifier-like symbols; operators fall through.
  if vim.fn.executable("rg") ~= 1 or word == "" or not word:match("^[%w_]") then
    return tags_or_docs(word)
  end

  local root = project_root()
  if not root then
    return tags_or_docs(word)
  end

  vim.system(
    { "rg", "--line-number", "--no-heading", "--column", "--word-regexp", "--smart-case", "--", word, "." },
    { text = true, cwd = root },
    function(res)
      vim.schedule(function()
        local entries = {}
        if res.code == 0 and res.stdout and res.stdout ~= "" then
          entries = parse_rg(vim.split(res.stdout, "\n", { trimempty = true }), root)
        end
        if #entries == 1 then
          jump_to(entries[1])
        elseif #entries > 1 then
          show_ripgrep_results(entries)
        else
          tags_or_docs(word) -- rg found nothing; fall to ctags -> docs
        end
      end)
    end
  )
end

--- Go to definition: LSP, then ripgrep, then ctags, then per-filetype docs.
function M.definition()
  local bufnr = vim.api.nvim_get_current_buf()
  local word = vim.fn.expand("<cword>")
  local method = vim.lsp.protocol.Methods.textDocument_definition
  local clients = vim.lsp.get_clients({ bufnr = bufnr, method = method })

  if #clients == 0 then
    return ripgrep_then_tags_then_docs(word)
  end

  local params = vim.lsp.util.make_position_params(0, clients[1].offset_encoding)
  vim.lsp.buf_request_all(bufnr, method, params, function(results)
    local found = false
    for _, res in pairs(results) do
      local r = res.result
      if r and not (type(r) == "table" and vim.tbl_isempty(r)) then
        found = true
        break
      end
    end
    if found then
      -- Re-run through the shared picker so behavior/UI matches the rest of the
      -- config (single result jumps, multiple show the picker).
      local ok, builtin = pcall(require, "telescope.builtin")
      if ok then
        builtin.lsp_definitions()
      else
        vim.lsp.buf.definition()
      end
    else
      ripgrep_then_tags_then_docs(word)
    end
  end)
end

return M
